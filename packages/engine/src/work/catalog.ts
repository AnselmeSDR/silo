export const PROFESSIONS: readonly Profession[] = ROWS.map(
  ([id, label, tasks, sectors, skills, shortage, continuous = false]) => ({
    id,
    label,
    tasks,
    sectors,
    skills,
    shortage,
    continuous,
  }),
);

const byId = new Map(PROFESSIONS.map((p) => [p.id, p]));

export const getProfession = (id: string): Profession => {
  const profession = byId.get(id);
  if (!profession) throw new Error(`unknown profession ${id}`);
  return profession;
};
